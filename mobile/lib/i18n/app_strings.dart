typedef StringMap = Map<String, String>;

class AppStrings {
  AppStrings(this.language);

  final LanguageCode language;

  String get(String key) => _bundles[language]?[key] ?? _bundles[LanguageCode.en]![key] ?? key;

  String get langSelect => get('lang.select');
  String get currencySelect => get('currency.select');
  String get welcome => get('common.welcome');

  /// Time-of-day salutation using the device local clock.
  String greetingForTime([DateTime? time]) {
    final hour = (time ?? DateTime.now()).hour;
    if (hour >= 5 && hour < 12) return get('greeting.morning');
    if (hour >= 12 && hour < 17) return get('greeting.afternoon');
    if (hour >= 17 && hour < 22) return get('greeting.evening');
    return get('greeting.night');
  }

  String get searchHint => get('header.searchPlaceholder');
  String get specialOffers => get('home.specialOffers');
  String get popularItems => get('home.popularItems');
  String get moreToExplore => get('home.moreToExplore');
  String get viewAll => get('common.seeAll');
  String get shopByCategory => get('home.shopByCategory');
  String get browseAll => get('home.browseAll');
  String get seeAll => get('common.seeAll');
  String get addToBasket => get('common.addToBasket');
  String get add => get('common.add');
  String get account => get('common.account');
  String get preferences => get('account.preferences');
  String get languageLabel => get('lang.select');
  String get currencyLabel => get('currency.select');
  String get liveRates => get('currency.liveRates');
  String get refreshRates => get('currency.refresh');
  String get freeDeliveryOver => get('cart.freeDeliveryOver');
  String get addedToBasket => get('cart.added');
  String get view => get('common.view');

  String currencyName(String code) => get('currency.names.$code');
  String langName(String code) => get('lang.$code');

  String homeRowTitle(String id) => get('home.rows.$id.title');
  String homeRowSubtitle(String id) => get('home.rows.$id.subtitle');
}

