import { readFileSync, writeFileSync } from 'node:fs';
const taxonomy = JSON.parse(readFileSync(new URL('../shared/search-taxonomy.json', import.meta.url), 'utf8'));
const file = new URL('../mobile/lib/utils/search_taxonomy.g.dart', import.meta.url);
const generated = `// Generated by scripts/generate-search-taxonomy.mjs; edit shared/search-taxonomy.json.\nconst searchPlurals = <String, String>${JSON.stringify(taxonomy.plurals, null, 2)};\n\nconst searchTagGroups = <Map<String, dynamic>>${JSON.stringify(taxonomy.groups, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== generated) throw new Error('Mobile search taxonomy is out of date');
} else writeFileSync(file, generated);
